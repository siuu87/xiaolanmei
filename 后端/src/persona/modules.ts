/**
 * 小蓝莓人设系统（五模块）
 *
 * 这份文本是「小蓝莓」这个角色的**唯一定义源**，随代码入库、由 `seedPersonaModules()`
 * 幂等播种进 `prompts` 表（global，sortOrder 10→50），再由 `buildSystemPrompt()` 拼进
 * 每次对话的 system 提示词。改这里 → 重启后端 → 人设即生效。
 *
 * 设计约定：
 * - `{{key}}` 由 `renderVariables()` 渲染：跨模块共享变量 > 内置变量 > 空。
 *   内置：`date` / `time` / `model` / `anniversary` / `loveDays`。
 * - **变量是跨模块共享的**：`buildSystemPrompt()` 会把所有模块的 `variables` 合成一张表，
 *   再统一渲染每个模块。也就是说模块二里写的 `{{user_nickname}}` 用的是模块一里那份值。
 * - 因此**同一个 key 只允许在一个模块里声明**（当前 `user_nickname` 归模块一）。
 *   如果两个模块都声明同一个 key，后声明的会盖掉先声明的，改另一个就等于白改——
 *   这是「静默失效」，比报错更难查。`verify-persona.js` 有断言守着这条。
 * - 已经确定的事实**直接写在正文里**（开箱即用），只有真正可个性化的槽位才用变量，
 *   并把已知值预填进 `variables`，这样既不空转、又能在「角色」面板里改。
 * - 模块五里的「预留槽位」是**未接线**的能力（触觉/头像交互），标注清楚，不写成已实现。
 */

export interface PersonaModule {
  /** 面板里显示的名字，也是幂等判重的键 */
  name: string;
  /** 正文（system 提示词片段） */
  content: string;
  /**
   * 变量默认值，可在「角色」面板里改。
   * **跨模块共享**：同一个 key 只在这一个模块声明，但任何模块的正文都能引用它。
   */
  variables: Record<string, string>;
  /** 拼接顺序 */
  sortOrder: number;
}

